// ── Pure helpers (no DOM). The browser wraps these in i18n.js. ──

export const LANG_CODES = LANGUAGES.map((l) => l.code);
export const LOCALES = { en: 'en-US', vi: 'vi-VN', ko: 'ko-KR', zh: 'zh-CN', ja: 'ja-JP' };

export function translate(lang, key) {
  return (translations[lang] && translations[lang][key]) || translations.en[key] || key;
}

export function typeFor(lang, typeLabel) {
  const key = TYPE_MAP[typeLabel];
  return key ? translate(lang, key) : (typeLabel || '-');
}

export function statusFor(lang, statusLabel, speed) {
  // Speed-based override: if AIS says "Under Way" but speed is near zero, show as stopped
  if (speed != null && speed <= 0.5) {
    const movingStatuses = ['Under Way Using Engine', 'Under Way Sailing'];
    if (!statusLabel || movingStatuses.includes(statusLabel)) return translate(lang, 'stopped');
  }
  if (statusLabel) {
    const key = STATUS_MAP[statusLabel];
    return key ? translate(lang, key) : statusLabel;
  }
  return speed > 0.5 ? translate(lang, 'moving') : translate(lang, 'stopped');
}

// Address of a localized page: English has no prefix, the others get /vi etc.
// '/' becomes '/vi/', '/storms' becomes '/vi/storms'.
export function localizedPath(lang, path) {
  if (!lang || lang === 'en') return path;
  return path === '/' ? `/${lang}/` : `/${lang}${path}`;
}
