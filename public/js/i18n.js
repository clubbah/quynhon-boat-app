const LANGUAGES = [
  { code: 'en', flag: 'us', label: 'English' },
  { code: 'vi', flag: 'vn', label: 'Ti\u1EBFng Vi\u1EC7t' },
  { code: 'ko', flag: 'kr', label: '\uD55C\uAD6D\uC5B4' },
  { code: 'zh', flag: 'cn', label: '\u4E2D\u6587' },
  { code: 'ja', flag: 'jp', label: '\u65E5\u672C\u8A9E' },
];

let currentLang = localStorage.getItem('lang') || 'en';

export function t(key) {
  return (translations[currentLang] && translations[currentLang][key])
    || translations['en'][key] || key;
}

export function getLang() { return currentLang; }
export function getLanguages() { return LANGUAGES; }

export function setLang(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('lang', lang);
  }
}

export function toggleLang() {
  const idx = LANGUAGES.findIndex(l => l.code === currentLang);
  const next = LANGUAGES[(idx + 1) % LANGUAGES.length].code;
  setLang(next);
  return next;
}

